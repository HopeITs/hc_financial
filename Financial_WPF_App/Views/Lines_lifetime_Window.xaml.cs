        private void Save_btn_Click(object sender, RoutedEventArgs e)
        {
            Save_btn.IsEnabled = false;
            try
            {
                if (!IsDirty)
                {
                    MessageBox.Show("There are no changes to save.", "Error", MessageBoxButton.OK, MessageBoxImage.None, MessageBoxResult.None, MessageBoxOptions.RtlReading | MessageBoxOptions.RightAlign);
                    return;
                }
                else
                {
                    Query = "";
                    Log_Query = "";

                    if (myDataGrid.ItemsSource != null)
                    {
                        DataView dataView = myDataGrid.ItemsSource as DataView;
                        for (int i = 0; i < dataView.Count; i++)
                        {
                            DataRowView row = dataView[i];
                            if (isDirty_list.Contains((int)row.Row["Line_ID"]))
                            {
                                Query += "UPDATE `line` SET `estimated_lifetime`='" + row.Row["Estimated Lifetime"].ToString() + "' WHERE ID = " + (int)row.Row["Line_ID"] + ";";
                                Log_Query = "UPDATE `line` SET `estimated_lifetime`=''" + row.Row["Estimated Lifetime"].ToString() + "'' WHERE ID = " + (int)row.Row["Line_ID"] + ";";
                                Query += " INSERT INTO log (form_name, title, affected_table, affected_id, details, additionaldetails, query, date, user) VALUES ('Lines_lifetime_Window', 'UPDATE', 'line', '" + (int)row.Row["Line_ID"] + "', CONCAT('Line Name = ', '" + Login.ReplaceQuotation(row.Row["Line"].ToString()) + "'), CONCAT('Estimated lifetime = ','"+ row.Row["Estimated Lifetime"].ToString() + "' ), '" + Log_Query + "', DATE(NOW()), '" + Properties.Settings.Default.username + "');";
                            }
                        }
                    }

                    Login.Execute_Query(Query);
                    MessageBox.Show("Saved successfully.", "Confirmation", MessageBoxButton.OK, MessageBoxImage.None, MessageBoxResult.None, MessageBoxOptions.RtlReading | MessageBoxOptions.RightAlign);
                    Fill_myDataGrid();
                }
            }
            catch (Exception ex)
            {
                if (Login.MyConn != null && Login.MyConn.State == ConnectionState.Open)
                {
                    Login.MyConn.Close();
                }
                if (ex.Message.Contains("Cannot delete or update a parent row"))
                {
                    MessageBox.Show("This item cannot be deleted due to its association with other data.", "Error", MessageBoxButton.OK, MessageBoxImage.None, MessageBoxResult.None, MessageBoxOptions.RtlReading | MessageBoxOptions.RightAlign);
                    Fill_myDataGrid();
                }
                else if (ex.Message.Contains("MySql") || ex.Message.Contains("MySQL"))
                { MessageBox.Show("please check your network and try again", "Error"); }
                else if (ex.Message.Contains("host"))
                { MessageBox.Show("please check the server or your network connection and try again", "Error"); }
                else if (ex.Message.Contains("Duplicate entry"))
                { MessageBox.Show("Error … There are duplicate values.", "Error", MessageBoxButton.OK, MessageBoxImage.None, MessageBoxResult.None, MessageBoxOptions.RtlReading | MessageBoxOptions.RightAlign); }
                else { MessageBox.Show(ex.Message, "Error"); }
            }
            finally
            {
                Save_btn.IsEnabled = true;
            }
        }
